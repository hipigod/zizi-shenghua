# 段落标记必须与 reclassify.py 写出的注释一致（阿拉伯数字）。
# 注意：主线 5、6 是重新分类后新增的，漏了会导致该线的字注入不进去。
LINE_SEC = {
    "caomu":  "主线1 · 草木之间",
    "riyue":  "主线2 · 日月星辰",
    "renwu":  "主线3 · 人来人往",
    "shuihuo":"主线4 · 水火之间",
    "houtu":  "主线5 · 厚土田园",
    "menhu":  "主线6 · 门户之间",
}


def entry(c):
    (ch, py, st, line, rare, qm, qd, ap, fam,
     origin, src, fun, words, note) = c
    s = '    "%s": { pinyin: "%s", structure: "%s", line: "%s", rare: %s, strokes: %d, quizMode: "%s"' % (
        ch, py, st, line, "true" if rare else "false", HW[ch], qm)
    if qd:
        s += ', quizDesc: "%s"' % qd
    if ap:
        s += ', assistPart: "%s"' % ap
    s += ', family: "%s",\n' % fam
    s += '      origin: "%s",\n' % origin
    s += '      originSource: "%s",\n' % src
    s += '      fun: "%s",\n' % fun
    s += '      words: [%s],' % ", ".join('"%s"' % w for w in words)
    s += ' note: "%s" },\n' % note if note else ' note: "" },\n'
    return s


def main():
    src = io.open(DATA_JS, encoding="utf-8").read()
    existing = set(re.findall(r'"(.)": \{', src[src.find("chars: {"):src.find("recipes:")]))

    # ---- 1. 字条目：按主线插入段落末尾 ----
    added = []
    for line_id, marker in LINE_SEC.items():
        items = [c for c in C if c[3] == line_id and c[0] not in existing]
        if not items:
            continue
        m = re.search(re.escape(marker), src)
        if not m:
            sys.stdout.write("找不到段落标记：%s\n" % marker)
            return 1
        pos = src.find("/* =====", m.end())          # 下一段注释
        if pos < 0:
            pos = src.find("\n  },", m.end())        # chars 结束
        block = "".join(entry(c) for c in items) + "\n"
        # 若插在段落最后一条（无尾逗号）之后，先补一个逗号
        if pos > 0 and src[pos - 1] == "}":
            block = ",\n" + block.lstrip("\n") if False else ",\n" + block
        src = src[:pos] + block + src[pos:]
        added += [c[0] for c in items]
        # 段落计数注释里的数字 +len(items)
        mm = re.search(re.escape(marker) + r"（(\d+)）", src)
        if mm:
            src = src[:mm.start(1)] + str(int(mm.group(1)) + len(items)) + src[mm.end(1):]

    # ---- 2. 配方 ----
    # 先做「木+口」的原地改写（会改变长度），再定位 recipes 结尾，避免偏移失效
    mm = re.search(r'\{ a: "木", b: "口", results: \[[^\]]*\][^\n]*\n', src)
    if mm and "束" not in mm.group(0):
        hs = ', hints: { "困": "口包木（外框是囗）", "呆": "口在木上", "杏": "口在木下", "束": "口捆在木腰" }'
        src = src[:mm.start()] + '{ a: "木", b: "口", results: ["困", "呆", "杏", "束"]' + hs + ' },\n' + src[mm.end():]

    rpos = src.find("  ],\n\n  /* ---------- 解锁表")
    if rpos < 0:
        sys.stdout.write("找不到 recipes 结尾\n")
        return 1
    need = []
    for a, b, results, hints in R:
        key = "".join(sorted([a, b]))
        if re.search(r'\{ a: "%s", b: "%s"' % (a, b), src) or \
           re.search(r'\{ a: "%s", b: "%s"' % (b, a), src):
            # 已存在：若是木+口这种需要追加结果的，单独处理
            continue
        h = ", hints: { %s }" % ", ".join('"%s": "%s"' % (k, v) for k, v in hints.items()) if hints else ""
        need.append('    { a: "%s", b: "%s", results: [%s]%s },\n'
                    % (a, b, ", ".join('"%s"' % x for x in results), h))

    if need:
        # recipes 最后一条没有尾逗号，插到它末尾补上
        head = src[:rpos].rstrip()
        if head[-1:] == "}":
            head += ","
        src = head + "\n" + "".join(need) + src[rpos:]

    io.open(DATA_JS, "w", encoding="utf-8").write(src)
    sys.stdout.write("新增字 %d 个：%s\n" % (len(added), "".join(added)))
    sys.stdout.write("新增配方 %d 条（木+口 追加「束」另计）\n" % len(need))
    return 0


if __name__ == "__main__":
    sys.exit(main())
