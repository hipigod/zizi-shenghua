/* ---------- 运行时索引：无序键（a|b 排序后拼接） ---------- */
(function buildIndex() {
  var idx = {};
  ZZSH.DATA.recipes.forEach(function (r) {
    var key = [r.a, r.b].sort().join("|");
    if (idx[key]) { throw new Error("配方键冲突: " + key); }
    idx[key] = r;
  });
  ZZSH.recipeIndex = idx;
})();

/* 便捷查询 */
ZZSH.findRecipe = function (a, b) {
  return ZZSH.recipeIndex[[a, b].sort().join("|")] || null;
};
